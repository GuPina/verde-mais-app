-- 0010 — o parâmetro de match das recorrências, e as sugestões dispensadas.
--
-- Até aqui uma recorrência só "pegava" o lançamento que ela mesma gerava. A
-- Netflix que entrava pela fatura importada, ou o salário digitado à mão,
-- ficava solto para sempre, e a recorrência mostrava o mês como não pago.
--
-- `recorrencia_regras` diz o que é "a mesma conta": um texto que a descrição
-- normalizada precisa conter, quanto o valor pode variar (NULL = qualquer
-- valor, para luz e água), quantos dias de folga no vencimento e, se quiser,
-- o cartão. Sem linha aqui vale a regra padrão do motor (src/lib/recorrencias).
--
-- `recorrencia_dispensas` guarda o "não é recorrência" que a pessoa disse no
-- rastreio, para a mesma sugestão não voltar toda vez.

CREATE TABLE IF NOT EXISTS recorrencia_regras (
  recorrencia_id integer PRIMARY KEY REFERENCES recorrencias(id) ON DELETE CASCADE,
  user_id        integer NOT NULL,
  texto          text NOT NULL,
  modo           text NOT NULL DEFAULT 'contem' CHECK (modo IN ('contem', 'comeca', 'igual')),
  tol_valor_pct  double precision NULL CHECK (tol_valor_pct IS NULL OR (tol_valor_pct >= 0 AND tol_valor_pct <= 100)),
  tol_dias       integer NOT NULL DEFAULT 5 CHECK (tol_dias BETWEEN 0 AND 15),
  cartao_id      integer NULL,
  auto_vincular  integer NOT NULL DEFAULT 1,
  atualizado_em  text DEFAULT to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_recorrencia_regras_user ON recorrencia_regras (user_id);

CREATE TABLE IF NOT EXISTS recorrencia_dispensas (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL,
  chave      text NOT NULL,
  criado_em  text DEFAULT to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS'),
  UNIQUE (user_id, chave)
);
