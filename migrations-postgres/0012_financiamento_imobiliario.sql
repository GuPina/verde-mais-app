-- 0012 — o financiamento imobiliário passa a enxergar o que foi pago de verdade.
--
-- A tela de Financiamentos só conhecia o contrato: as parcelas que ela mesma
-- gera e uma tabela de entrada à parte, que ninguém preenchia. A entrada que o
-- Gustavo parcelou (dezenas de lançamentos de R$ 150 a R$ 600), a evolução de
-- obra mês a mês, o seguro, o ITBI — tudo isso vive em Despesas, e o
-- financiamento não via nada.
--
-- `financiamento_vinculos` liga uma despesa a um financiamento com um PAPEL.
-- A despesa continua em Despesas; o vínculo só diz o que ela é. Apagar a
-- despesa apaga o vínculo; apagar o financiamento também (a despesa fica).

CREATE TABLE IF NOT EXISTS financiamento_vinculos (
  despesa_id       integer PRIMARY KEY REFERENCES despesas(id) ON DELETE CASCADE,
  financiamento_id integer NOT NULL REFERENCES financiamentos(id) ON DELETE CASCADE,
  user_id          integer NOT NULL,
  papel            text NOT NULL CHECK (papel IN ('entrada', 'obra', 'parcela', 'seguro', 'extra')),
  criado_em        text DEFAULT to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS idx_fin_vinculos_fin ON financiamento_vinculos (financiamento_id, papel);
CREATE INDEX IF NOT EXISTS idx_fin_vinculos_user ON financiamento_vinculos (user_id);

-- Os nomes que a pessoa confirmou para cada papel ("ENTRADA APTO", "EVOLUCAO
-- DE OBRA"): o próximo lançamento com esse nome entra vinculado sozinho.
CREATE TABLE IF NOT EXISTS financiamento_apelidos (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  financiamento_id integer NOT NULL REFERENCES financiamentos(id) ON DELETE CASCADE,
  user_id          integer NOT NULL,
  papel            text NOT NULL,
  texto            text NOT NULL,
  UNIQUE (financiamento_id, papel, texto)
);

-- O % da obra ao longo do tempo. Antes só existia o número atual.
CREATE TABLE IF NOT EXISTS financiamento_obra_hist (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  financiamento_id integer NOT NULL REFERENCES financiamentos(id) ON DELETE CASCADE,
  user_id          integer NOT NULL,
  data             text NOT NULL,
  pct              double precision NOT NULL,
  UNIQUE (financiamento_id, data)
);

